"""Embedding generation for the knowledge base.

Runs after a product row has already been committed (see crud.create_product /
update_product). That ordering is deliberate: hand-curated prose is the
expensive thing to lose, so it is made durable before anything that can fail
over the network is attempted. A product with stale or missing embeddings is
recoverable with sync_embeddings(); a product that never saved is retyped.

Source text is built from templates rather than generated by an LLM. Two
reasons: an LLM can introduce facts that are not in the record, which is
corrosive for a knowledge base whose premise is hallucination resistance; and
it would be non-deterministic, which breaks the staleness check below -- that
check works precisely because identical input produces byte-identical text.

See ADR-0005.
"""

from decimal import Decimal
from uuid import UUID

from openai import AsyncOpenAI

from app import db
from app.schemas import Product

EMBEDDING_MODEL = "text-embedding-3-large"

# Requested explicitly rather than taking the model's native 3072, because
# product_embeddings.embedding is vector(1536). A mismatch fails on insert.
EMBEDDING_DIMENSIONS = 1536

_client: AsyncOpenAI | None = None


def get_client() -> AsyncOpenAI:
    """Timeout and retries are sized against the 60s Lambda budget.

    The SDK retries timeouts, so worst-case wall clock is
    timeout x (max_retries + 1) = 30s, leaving the request half its budget for
    everything else. The SDK defaults (10 minutes, 2 retries) would allow 30
    minutes -- the Lambda would be killed long before the client gave up.
    """
    global _client
    if _client is None:
        _client = AsyncOpenAI(timeout=10.0, max_retries=2)
    return _client


# ---------------------------------------------------------------------------
# Source text
# ---------------------------------------------------------------------------


def _num(value: Decimal | int | None) -> str | None:
    """Render 101.0 as "101" and 50.50 as "50.5".

    Integral values are checked BEFORE normalize(), which renders Decimal("90")
    as "9E+1" -- correct scientific notation, useless in a sentence.
    """
    if value is None:
        return None
    if isinstance(value, Decimal):
        if value == value.to_integral_value():
            return str(value.to_integral_value())
        return str(value.normalize())
    return str(value)


def _words(value: str | None) -> str | None:
    return value.replace("_", " ") if value else None


def _join(sentences: list[str | None]) -> str:
    return " ".join(s.strip() for s in sentences if s and s.strip())


def _identity(product: Product, producer: str | None) -> str:
    """The opening sentence, shared by all three types.

    Every embedding needs enough context to be self-contained -- a bare
    tasting note does not say what it is a tasting note for.

    `producer` is passed only when it is unambiguous (not a sourced bottle);
    otherwise full_profile carries the distiller/bottler split in its own
    sentence and this stays neutral.
    """
    subcategory = _words(product.subcategory) or _words(product.category)
    region = _words(product.region)

    # "Kentucky" + "Kentucky straight bourbon" would read "a Kentucky Kentucky
    # straight bourbon". Subcategories routinely name their own region.
    if region and region.lower() in subcategory.lower():
        region = None

    kind = " ".join(part for part in (region, subcategory) if part)
    sentence = f"{product.canonical_name} is a {kind}"
    if producer:
        sentence += f" produced by {producer}"
    return sentence + "."


def build_source_texts(
    product: Product,
    distiller: str | None = None,
    bottler: str | None = None,
) -> dict[str, str]:
    """Natural-language prose per embedding type.

    A type is omitted entirely when its defining field is empty. Embedding
    "Wild Turkey 101 is a bourbon." into the tasting_notes slot would match
    flavor queries while carrying no flavor information -- worse than absent,
    because retrieval cannot tell that it is uninformative.
    """
    texts: dict[str, str] = {}
    sourced = bool(bottler and distiller and bottler != distiller)
    identity = _identity(product, None if sourced else (distiller or bottler))

    # --- full_profile: the overall picture --------------------------------
    spec = None
    if product.proof and product.abv_pct:
        spec = f"Bottled at {_num(product.proof)} proof ({_num(product.abv_pct)}% ABV)."
    elif product.abv_pct:
        spec = f"Bottled at {_num(product.abv_pct)}% ABV."

    age = None
    if product.age_statement:
        age = f"Age: {product.age_statement}."
    elif product.age_years:
        age = f"Aged {_num(product.age_years)} years."

    sourcing = f"Distilled by {distiller} and bottled by {bottler}." if sourced else None

    character = None
    traits = list(product.style_tags) + list(product.flavor_profile)
    if traits:
        character = f"Character: {', '.join(_words(t) for t in traits)}."

    market = None
    if product.availability:
        market = f"{_words(product.availability).capitalize()}."
        low, high = product.typical_retail_low_usd, product.typical_retail_high_usd
        if low and high:
            market += f" Typically ${_num(low)}-${_num(high)} at retail."
        elif product.msrp_usd:
            market += f" MSRP ${_num(product.msrp_usd)}."

    full = _join(
        [identity, spec, age, sourcing, character, product.description, market]
    )
    if full != identity:
        texts["full_profile"] = full

    # --- tasting_notes: flavor queries ------------------------------------
    if product.tasting_notes:
        texts["tasting_notes"] = _join(
            [
                identity,
                spec,
                product.tasting_notes,
                f"Flavor profile: {', '.join(product.flavor_profile)}."
                if product.flavor_profile
                else None,
            ]
        )

    # --- community_sentiment: reputation queries --------------------------
    if product.community_sentiment:
        texts["community_sentiment"] = _join(
            [identity, product.community_sentiment, market]
        )

    return texts


async def _source_texts_for(product: Product) -> dict[str, str]:
    """Resolves producer names, which the templates need but the row lacks."""
    ids = [i for i in (product.distiller_id, product.bottler_id) if i]
    names: dict[UUID, str] = {}
    if ids:
        rows = await db.fetch(
            "SELECT id, name FROM producers WHERE id = ANY($1)", list(set(ids))
        )
        names = {row["id"]: row["name"] for row in rows}
    return build_source_texts(
        product,
        distiller=names.get(product.distiller_id),
        bottler=names.get(product.bottler_id),
    )


# ---------------------------------------------------------------------------
# Generation
# ---------------------------------------------------------------------------


async def _embed(texts: list[str]) -> list[list[float]]:
    """One request for all texts -- the endpoint accepts an array."""
    response = await get_client().embeddings.create(
        model=EMBEDDING_MODEL,
        dimensions=EMBEDDING_DIMENSIONS,
        input=texts,
    )
    # The API preserves input order, but index is authoritative.
    return [item.embedding for item in sorted(response.data, key=lambda d: d.index)]


async def sync_embeddings(product_id: UUID, force: bool = False) -> dict[str, int]:
    """Bring a product's embeddings in line with its current content.

    Returns counts of what happened. Only types whose source text actually
    changed are sent to OpenAI, so editing a field that appears in no template
    (`notes`, `pricing_notes`) costs no API call at all.

    Pass force=True to regenerate regardless -- used by the manual
    "Regenerate" action when a vector is suspected bad despite matching text.
    """
    row = await db.fetchrow("SELECT * FROM products WHERE id = $1", product_id)
    if row is None:
        return {"written": 0, "removed": 0, "unchanged": 0}

    desired = await _source_texts_for(Product(**dict(row)))

    stored = {
        r["embedding_type"]: r["source_text"]
        for r in await db.fetch(
            "SELECT embedding_type, source_text FROM product_embeddings "
            "WHERE product_id = $1",
            product_id,
        )
    }

    # A type that no longer has source text (the curator cleared tasting_notes)
    # must lose its row, or a stale vector keeps matching queries forever.
    obsolete = [t for t in stored if t not in desired]
    if obsolete:
        await db.execute(
            "DELETE FROM product_embeddings "
            "WHERE product_id = $1 AND embedding_type = ANY($2)",
            product_id,
            obsolete,
        )

    stale = {
        etype: text
        for etype, text in desired.items()
        if force or stored.get(etype) != text
    }
    if not stale:
        return {"written": 0, "removed": len(obsolete), "unchanged": len(desired)}

    types = list(stale)
    vectors = await _embed([stale[t] for t in types])

    for etype, vector in zip(types, vectors):
        await db.execute(
            "INSERT INTO product_embeddings "
            "(product_id, embedding_type, embedding, source_text) "
            "VALUES ($1, $2, $3, $4) "
            "ON CONFLICT (product_id, embedding_type) DO UPDATE "
            "SET embedding = EXCLUDED.embedding, source_text = EXCLUDED.source_text",
            product_id,
            etype,
            # Passed as a plain list: db._init_connection registers the
            # pgvector codec on every connection, which encodes it natively.
            # str(vector) would be rejected -- the codec wants list/ndarray.
            vector,
            stale[etype],
        )

    return {
        "written": len(stale),
        "removed": len(obsolete),
        "unchanged": len(desired) - len(stale),
    }


async def embedding_status(product_id: UUID) -> dict[str, list[str]]:
    """What the list view's indicator column renders.

    Costs no API call: staleness is a string comparison against the stored
    source_text, so the whole knowledge base can be checked for free.
    """
    row = await db.fetchrow("SELECT * FROM products WHERE id = $1", product_id)
    if row is None:
        return {"current": [], "stale": [], "missing": []}

    desired = await _source_texts_for(Product(**dict(row)))
    stored = {
        r["embedding_type"]: r["source_text"]
        for r in await db.fetch(
            "SELECT embedding_type, source_text FROM product_embeddings "
            "WHERE product_id = $1",
            product_id,
        )
    }

    return {
        "current": sorted(t for t in desired if stored.get(t) == desired[t]),
        "stale": sorted(
            t for t in desired if t in stored and stored[t] != desired[t]
        ),
        "missing": sorted(t for t in desired if t not in stored),
    }
